// Role 4: Report tab of the Investigation Workspace. In live mode it requests GET /cases/{id}/report?format=pdf and,
// only if the server returns a PDF, previews it and offers that exact file for download. Demo mode has no backend to
// generate a report, so it shows what the report will contain, built from the loaded data, with no download button.
import { useEffect, useState } from "react";
import { Alert, ReportIcon, Refresh } from "../components/console/icons";
import { fetchReportPdf } from "../api/client";
import type { EvidenceItem, Finding } from "../api/types";
import { statusOf } from "../features/dashboard/components/FindingsPanel";
import type { EvidenceSourceKind } from "../features/vault/evidenceSource";

type PdfState = { status: "idle" } | { status: "loading" } | { status: "error"; message: string } | { status: "ready"; url: string };

function Contents({ evidence, findings }: { evidence: EvidenceItem[] | null; findings: Finding[] | null }) {
  const approved = findings?.filter(f => statusOf(f) === "approved") ?? [];
  const sections: [string, string][] = [
    ["Case summary", "Case ID and the period the evidence covers"],
    [
      "Evidence table",
      evidence ? `${evidence.length} items with SHA-256 and intake time, laid out along BSA Section 63 certificate fields` : "Evidence with SHA-256 and intake time"
    ],
    ["Custody log", evidence ? `${evidence.reduce((n, e) => n + e.custody.length, 0)} custody entries` : "Every custody entry"],
    ["Approved findings", findings ? `${approved.length} of ${findings.length} findings currently approved, each with its evidence IDs` : "Findings the investigator approved"],
    ["Reviewer approval", "Who approved the findings"]
  ];
  return (
    <ol className="mt-4 grid gap-2.5 sm:grid-cols-2">
      {sections.map(([title, body], i) => (
        <li key={title} className="flex gap-3 rounded-xl border border-white/[0.07] bg-white/[0.02] p-3.5">
          <span className="flex size-7 shrink-0 items-center justify-center rounded-lg border border-trace/35 text-[12px] text-trace-soft">{i + 1}</span>
          <span>
            <span className="block text-[14px] text-white">{title}</span>
            <span className="mt-0.5 block text-[12.5px] text-soft/70">{body}</span>
          </span>
        </li>
      ))}
    </ol>
  );
}

export default function Report({
  caseId,
  sourceKind,
  evidence,
  findings
}: {
  caseId: string;
  sourceKind: EvidenceSourceKind;
  evidence: EvidenceItem[] | null;
  findings: Finding[] | null;
}) {
  const [pdf, setPdf] = useState<PdfState>({ status: "idle" });

  useEffect(() => () => {
    if (pdf.status === "ready") URL.revokeObjectURL(pdf.url);
  }, [pdf]);

  const generate = async () => {
    setPdf({ status: "loading" });
    try {
      const blob = await fetchReportPdf(caseId);
      setPdf({ status: "ready", url: URL.createObjectURL(blob) });
    } catch (error) {
      setPdf({ status: "error", message: error instanceof Error ? error.message : "The report could not be generated." });
    }
  };

  return (
    <div className="grid gap-6 xl:grid-cols-[minmax(0,1fr)_360px]">
      <div className="min-w-0">
        {sourceKind === "demo" ? (
          <div className="flex gap-4 rounded-xl border border-amber-300/25 bg-amber-300/[0.05] p-5">
            <ReportIcon size={26} className="shrink-0 text-amber-300" />
            <div className="text-[13.5px]">
              <p className="font-semibold text-white">No report in demo mode</p>
              <p className="mt-1 text-soft/80">
                The PDF is generated by the backend from reviewed findings. Demo data has no backend behind it, so there is nothing to preview or
                download. Switch to the live API to request the report.
              </p>
            </div>
          </div>
        ) : pdf.status === "ready" ? (
          <div>
            <div className="flex flex-wrap items-center justify-between gap-3">
              <p className="text-[13.5px] text-soft/80">Preview of the PDF returned by the server.</p>
              <a
                href={pdf.url}
                download={`${caseId}-report.pdf`}
                className="rounded-lg bg-alert px-4 py-2 text-[13.5px] font-medium text-white shadow-[0_0_18px_rgba(239,43,60,0.35)] hover:bg-[#ff3a4a]"
              >
                Save PDF
              </a>
            </div>
            <iframe title={`${caseId} report`} src={pdf.url} className="mt-3 h-[640px] w-full rounded-xl border border-trace/25 bg-white" />
          </div>
        ) : (
          <div className="flex flex-col items-start gap-4 rounded-xl border border-trace/25 bg-trace/[0.04] p-5">
            <div className="flex gap-4">
              <ReportIcon size={26} className="shrink-0 text-trace-soft" />
              <div className="text-[13.5px]">
                <p className="font-semibold text-white">Investigator-reviewed report</p>
                <p className="mt-1 text-soft/80">Requests GET /cases/{caseId}/report?format=pdf. Only a PDF the server returns is shown or saved.</p>
              </div>
            </div>
            {pdf.status === "error" && (
              <p role="alert" className="flex gap-2 text-[13px] text-alert-soft">
                <Alert size={16} className="mt-px shrink-0" /> {pdf.message}
              </p>
            )}
            <button
              type="button"
              onClick={generate}
              disabled={pdf.status === "loading"}
              className="inline-flex items-center gap-2 rounded-lg border border-trace/50 bg-trace/10 px-4 py-2.5 text-[13.5px] text-white transition hover:bg-trace/20 disabled:opacity-50"
            >
              {pdf.status === "error" && <Refresh size={15} />}
              {pdf.status === "loading" ? "Requesting report…" : pdf.status === "error" ? "Try again" : "Request report"}
            </button>
          </div>
        )}
        <p className="mt-3 text-[12px] text-muted">The report is investigator support material aligned with BSA Section 63 certificate fields. It is not a legal certificate.</p>
      </div>

      <div className="min-w-0">
        <h3 className="text-[14.5px] font-semibold text-white">What the report contains</h3>
        <Contents evidence={evidence} findings={findings} />
      </div>
    </div>
  );
}
